//! Real-content test gate: requires ffmpeg/ffprobe on PATH.
//!
//! Proves the packager end-to-end against ffmpeg-generated MP4s
//! (`scripts/gen_fixtures.sh`), each covering a distinct code path:
//!  1. parser vs ffprobe ground truth (frame counts, duration)
//!  2. Case B: index → built init + assembled segments → ffmpeg decodes it
//!  3. Case A: fragmented source → init (ftyp + source moov) + passthrough
//!  4. every segment decodes standalone; playlists consumed by ffprobe
//!  5. A/V timing equals ffmpeg's own CMAF remux of the same source
//!  6. per-fixture expectations (codec strings, edit lists, GOP handling,
//!     VFR durations, fragment boundaries, audio-only, multi-audio, …)

use gorani_media::index_builder::BuildOptions;
use gorani_media::indexer::{head_and_tail_ranges, index_bytes, index_lazy};
use gorani_media::moof_builder::build_segment_from_index;
use gorani_media::moov_builder::{build_init_segment, ftyp_bytes};
use gorani_media::playlist;
use gorani_media::readplan;
use gorani_media::schema::*;
use std::path::{Path, PathBuf};
use std::process::Command;

// Generated by scripts/gen-media-fixtures.sh (ffmpeg); the tests SKIP when
// it has not been run. Under tests/output/, which git ignores.
const FIX_DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../tests/output/fixtures-real");

fn ffmpeg_available() -> bool {
    Command::new("ffmpeg")
        .arg("-version")
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// (fixture, expected kind, has video, has audio)
fn fixtures() -> Vec<(&'static str, SourceKind, bool, bool)> {
    vec![
        ("bframes", SourceKind::Regular, true, true),
        ("regular", SourceKind::Regular, true, true),
        ("faststart", SourceKind::Regular, true, true),
        ("moovend_heavy", SourceKind::Regular, true, true),
        ("hevc", SourceKind::Regular, true, false),
        ("hevc_bframes", SourceKind::Regular, true, true),
        ("fragmented", SourceKind::Fragmented, true, true),
        ("cmaf_dash", SourceKind::Fragmented, true, true),
        ("audio_only", SourceKind::Regular, false, true),
        ("video_only", SourceKind::Regular, true, false),
        ("opus", SourceKind::Regular, true, true),
        ("ac3", SourceKind::Regular, true, true),
        ("multi_audio", SourceKind::Regular, true, true),
        ("long_gop", SourceKind::Regular, true, true),
        ("vfr", SourceKind::Regular, true, true),
        ("uhd", SourceKind::Regular, true, false),
        ("big_lazy", SourceKind::Regular, true, true),
    ]
}

fn fixture_path(name: &str, ext: &str) -> PathBuf {
    Path::new(FIX_DIR).join(format!("{name}.{ext}"))
}

fn ffprobe_json(path: &Path, args: &[&str]) -> serde_json::Value {
    let out = Command::new("ffprobe")
        .args(["-v", "quiet", "-print_format", "json"])
        .args(args)
        .arg(path)
        .output()
        .expect("ffprobe");
    serde_json::from_slice(&out.stdout).unwrap_or(serde_json::Value::Null)
}

/// ffprobe frame count of the first stream of `kind` ("v" or "a")
fn count_frames(path: &Path, kind: &str) -> u64 {
    let sel = format!("{kind}:0");
    let v = ffprobe_json(
        path,
        &[
            "-count_frames",
            "-select_streams",
            &sel,
            "-show_entries",
            "stream=nb_read_frames",
        ],
    );
    v["streams"][0]["nb_read_frames"]
        .as_str()
        .unwrap_or("0")
        .parse()
        .unwrap_or(0)
}

/// ffprobe packet count of the first stream of `kind` — what a remuxer must
/// preserve exactly (decoded frame counts can differ by an edit-list trim
/// the decoder applies to the source but not to CMAF output).
fn count_packets(path: &Path, kind: &str) -> u64 {
    let sel = format!("{kind}:0");
    let v = ffprobe_json(
        path,
        &[
            "-count_packets",
            "-select_streams",
            &sel,
            "-show_entries",
            "stream=nb_read_packets",
        ],
    );
    v["streams"][0]["nb_read_packets"]
        .as_str()
        .unwrap_or("0")
        .parse()
        .unwrap_or(0)
}

fn ffprobe_duration_ms(path: &Path) -> u64 {
    let v = ffprobe_json(path, &["-show_entries", "format=duration"]);
    (v["format"]["duration"]
        .as_str()
        .unwrap_or("0")
        .parse::<f64>()
        .unwrap_or(0.0)
        * 1000.0) as u64
}

/// (pts, dts) of the first `n` video packets
fn first_video_packets(path: &Path, n: usize) -> Vec<(i64, i64)> {
    let v = ffprobe_json(
        path,
        &["-select_streams", "v:0", "-show_entries", "packet=pts,dts"],
    );
    v["packets"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .take(n)
        .map(|p| {
            (
                p["pts"].as_i64().unwrap_or(0),
                p["dts"].as_i64().unwrap_or(0),
            )
        })
        .collect()
}

/// (video start_time, audio start_time) in seconds as ffprobe sees them
fn stream_starts(path: &Path) -> (Option<f64>, Option<f64>) {
    let v = ffprobe_json(path, &["-show_entries", "stream=codec_type,start_time"]);
    let mut vs = None;
    let mut as_ = None;
    for s in v["streams"].as_array().cloned().unwrap_or_default() {
        let st = s["start_time"].as_str().and_then(|x| x.parse::<f64>().ok());
        match s["codec_type"].as_str() {
            Some("video") => vs = st,
            Some("audio") => as_ = st,
            _ => {}
        }
    }
    (vs, as_)
}

/// Index a fixture exactly like the worker/CLI do (head+tail buffers), and
/// cross-check that the lazy walker yields the identical index.
fn index_fixture(name: &str, src: &[u8]) -> MediaIndex {
    let size = src.len() as u64;
    let ranges = head_and_tail_ranges(size);
    let tail = if ranges.tail_len > 0 {
        Some((
            &src[(size - ranges.tail_len) as usize..],
            size - ranges.tail_len,
        ))
    } else {
        None
    };
    let source = || SourceInfo {
        key: format!("{name}.mp4"),
        size,
        etag: None,
    };
    let idx = index_bytes(
        source(),
        &src[..ranges.head_len as usize],
        0,
        tail,
        &BuildOptions::default(),
    )
    .unwrap();
    let mut reader = |off: u64, len: u64| -> gorani_media::Result<Vec<u8>> {
        Ok(src[off as usize..(off + len).min(size) as usize].to_vec())
    };
    let lazy = index_lazy(source(), &mut reader, &BuildOptions::default()).unwrap();
    assert_eq!(
        lazy, idx,
        "{name}: lazy walker index differs from head/tail index"
    );
    idx
}

/// Build segment `n` exactly like the worker does: plan coalesced reads over
/// the union of all track ranges, slice per-track payloads, assemble.
fn segment_bytes(idx: &MediaIndex, n: usize, src: &[u8]) -> Vec<u8> {
    let seg = &idx.segments[n];
    if let Some(fr) = seg.fragment_range {
        return src[fr.offset as usize..fr.end() as usize].to_vec();
    }
    let wanted = readplan::segment_ranges(seg);
    let plan = readplan::plan_reads(
        &wanted,
        readplan::DEFAULT_MAX_GAP,
        readplan::DEFAULT_MAX_BLOCK,
    );
    assert!(
        plan.len() <= 2,
        "segment {n}: interleaved A/V should coalesce to ~1 read, got {}",
        plan.len()
    );
    let blocks: Vec<(ByteRange, Vec<u8>)> = plan
        .iter()
        .map(|r| (*r, src[r.offset as usize..r.end() as usize].to_vec()))
        .collect();
    let payloads: Vec<Vec<u8>> = seg
        .tracks
        .iter()
        .map(|st| readplan::concat_ranges(&blocks, &st.byte_ranges).unwrap())
        .collect();
    build_segment_from_index(idx, n, payloads).unwrap()
}

fn init_bytes(idx: &MediaIndex, src: &[u8]) -> Vec<u8> {
    match idx.kind {
        SourceKind::Regular => build_init_segment(idx).unwrap(),
        SourceKind::Fragmented => {
            let mr = idx.moov_range.unwrap();
            let mut out = ftyp_bytes();
            out.extend_from_slice(&src[mr.offset as usize..mr.end() as usize]);
            out
        }
    }
}

/// Top-level box types of a byte buffer.
fn top_level_types(buf: &[u8]) -> Vec<String> {
    let mut out = Vec::new();
    gorani_media::boxes::walk_top_level(buf, 0, |h| {
        out.push(String::from_utf8_lossy(&h.box_type).to_string());
        true
    })
    .unwrap();
    out
}

/// Fixture-specific expectations — the "does the index describe what the
/// encoder produced" half of the gate.
fn check_expectations(name: &str, idx: &MediaIndex, src: &[u8]) {
    let ts = idx.primary_timescale() as f64;
    let max_seg_s = idx.segments.iter().map(|s| s.duration).max().unwrap_or(0) as f64 / ts;
    match name {
        "bframes" => {
            let v = idx.video_track().unwrap();
            assert!(v.edit_media_time > 0, "bframes: video edit list expected");
            assert!(
                idx.segments[0].tracks[0].cts_deltas.len() > 1,
                "bframes: composition offsets expected"
            );
            assert!(v.codec_string.starts_with("avc1."));
        }
        "hevc" => {
            let v = idx.video_track().unwrap();
            assert!(
                v.codec_string.starts_with("hvc1.1.6.L")
                    || v.codec_string.starts_with("hev1.1.6.L"),
                "{}",
                v.codec_string
            );
            assert!(idx.audio_track().is_none());
        }
        "hevc_bframes" => {
            let v = idx.video_track().unwrap();
            assert!(
                v.codec_string.starts_with("hev1.1.6.L"),
                "{}",
                v.codec_string
            );
            assert!(v.edit_media_time > 0, "hevc_bframes: edit list expected");
            assert_eq!(idx.audio_track().unwrap().timescale, 48000);
        }
        "cmaf_dash" | "fragmented" => {
            assert_eq!(idx.kind, SourceKind::Fragmented);
            for (i, seg) in idx.segments.iter().enumerate() {
                let fr = seg.fragment_range.unwrap();
                let bytes = &src[fr.offset as usize..fr.end() as usize];
                let types = top_level_types(bytes);
                assert_eq!(types[0], "moof", "{name}: segment {i} must start with moof");
                assert!(
                    types.iter().all(|t| t == "moof" || t == "mdat"),
                    "{name}: segment {i} carries non-fragment boxes {types:?} (sidx/styp/mfra must be excluded)"
                );
                // exact per-track start times come from tfdt
                for st in &seg.tracks {
                    assert!(st.start_dts.is_some());
                }
            }
        }
        "audio_only" => {
            assert!(idx.video_track().is_none());
            let a = idx.audio_track().unwrap();
            assert_eq!(
                idx.primary_track_id, a.id,
                "audio-only: the audio track is primary"
            );
            assert!(a.codec_string.starts_with("mp4a.40."));
            assert!(idx.segments.len() >= 2);
        }
        "video_only" | "uhd" => {
            assert!(idx.audio_track().is_none());
            let v = idx.video_track().unwrap();
            if name == "uhd" {
                assert_eq!((v.width, v.height), (3840, 2160));
            }
            for seg in &idx.segments {
                assert_eq!(seg.tracks.len(), 1);
            }
        }
        "opus" => assert_eq!(idx.audio_track().unwrap().codec_string, "Opus"),
        "ac3" => assert_eq!(idx.audio_track().unwrap().codec_string, "ac-3"),
        "multi_audio" => {
            // only the first audio track is served (players cannot consume
            // several audio tracks muxed into one CMAF segment)
            assert_eq!(
                idx.tracks.len(),
                2,
                "multi_audio: video + first audio only, got {:?}",
                idx.tracks.iter().map(|t| t.id).collect::<Vec<_>>()
            );
            for seg in &idx.segments {
                assert_eq!(seg.tracks.len(), 2);
            }
        }
        "long_gop" => {
            // 10-second GOPs with a 6-second target → segments are whole GOPs
            assert!(
                max_seg_s > 9.5 && max_seg_s < 10.5,
                "long_gop: max segment {max_seg_s}s"
            );
            assert_eq!(idx.segments.len(), 3);
        }
        "vfr" => {
            let any_deltas = idx
                .segments
                .iter()
                .any(|s| s.tracks[0].sample_duration_deltas.is_some());
            assert!(any_deltas, "vfr: per-sample duration deltas expected");
        }
        "big_lazy" => {
            assert!(src.len() as u64 > gorani_media::indexer::HEAD_MAX);
            assert!(idx.segments.len() >= 3);
        }
        _ => {}
    }
    // universal invariants
    assert!(
        max_seg_s <= 12.0,
        "{name}: segment longer than 12s ({max_seg_s})"
    );
    for seg in &idx.segments {
        assert_eq!(
            seg.tracks[0].track_id, idx.primary_track_id,
            "{name}: primary track must come first"
        );
        assert!(seg.duration > 0);
    }
    let mut prev_end = 0i64;
    for seg in &idx.segments {
        if idx.kind == SourceKind::Regular {
            assert_eq!(
                seg.start_dts, prev_end,
                "{name}: segments must be contiguous"
            );
        }
        prev_end = seg.start_dts + seg.duration as i64;
    }
}

#[test]
fn gate_real_content() {
    if !ffmpeg_available() {
        eprintln!("SKIP: ffmpeg not on PATH");
        return;
    }
    if !Path::new(FIX_DIR).exists() {
        eprintln!("SKIP: run scripts/gen_fixtures.sh first");
        return;
    }
    let tmp = std::env::temp_dir().join("r2hls-gate");
    std::fs::create_dir_all(&tmp).unwrap();

    for (name, kind, has_video, has_audio) in fixtures() {
        let src_path = fixture_path(name, "mp4");
        if !src_path.exists() {
            eprintln!("SKIP {name}: fixture missing (SMALL=1 or old gen_fixtures.sh?)");
            continue;
        }
        eprintln!("--- gate: {name} ({kind:?})");
        let src = std::fs::read(&src_path).unwrap();
        let idx = index_fixture(name, &src);
        assert_eq!(idx.kind, kind, "{name}: wrong source kind");
        assert_eq!(
            idx.video_track().is_some(),
            has_video,
            "{name}: video track presence"
        );
        assert_eq!(
            idx.audio_track().is_some(),
            has_audio,
            "{name}: audio track presence"
        );
        check_expectations(name, &idx, &src);

        // duration vs ffprobe within 100ms
        let src_duration = ffprobe_duration_ms(&src_path);
        let drift = idx.duration_ms.abs_diff(src_duration);
        assert!(
            drift <= 100,
            "{name}: index duration {} vs ffprobe {src_duration}",
            idx.duration_ms
        );

        // assemble the whole presentation: init + every segment
        let mut assembled = init_bytes(&idx, &src);
        for n in 0..idx.segments.len() {
            assembled.extend(segment_bytes(&idx, n, &src));
        }
        let out_path = tmp.join(format!("{name}-assembled.mp4"));
        std::fs::write(&out_path, &assembled).unwrap();

        // decode check, duration within 100ms. Video: decoded frame counts
        // must match. Audio: PACKET counts must match — decoded frame counts
        // differ by the priming frame the decoder discards on the source's
        // edit list but not on CMAF output (ffmpeg's own remux behaves the
        // same; see the oracle below).
        let kind_sel = if has_video { "v" } else { "a" };
        let (frames_src, frames_out) = if has_video {
            (count_frames(&src_path, "v"), count_frames(&out_path, "v"))
        } else {
            (count_packets(&src_path, "a"), count_packets(&out_path, "a"))
        };
        assert_eq!(
            frames_src, frames_out,
            "{name}: assembled stream decodes to a different frame/packet count"
        );
        assert!(frames_src > 0);
        if has_audio {
            let a_src = count_packets(&src_path, "a");
            let a_out = count_packets(&out_path, "a");
            assert_eq!(a_src, a_out, "{name}: audio packet count differs");
            assert!(a_out > 0);
        }
        // every packet of every served track survives the remux
        let v_src = count_packets(&src_path, kind_sel);
        let v_out = count_packets(&out_path, kind_sel);
        assert_eq!(v_src, v_out, "{name}: packet count differs");
        let dur_out = ffprobe_duration_ms(&out_path);
        assert!(
            dur_out.abs_diff(src_duration) <= 100,
            "{name}: assembled duration {dur_out} vs source {src_duration}"
        );

        // A/V timing oracle: ffmpeg's OWN CMAF remux of the same source must
        // probe identically (start times within 1ms, first video packets'
        // (pts, dts) exactly equal).
        if kind == SourceKind::Regular && has_video {
            let reference = tmp.join(format!("{name}-ffmpeg-cmaf.mp4"));
            let remux = |with_audio: bool| -> bool {
                let mut cmd = Command::new("ffmpeg");
                cmd.args(["-v", "error", "-y", "-i"])
                    .arg(&src_path)
                    .args(["-map", "0:v:0"]);
                if with_audio {
                    cmd.args(["-map", "0:a:0"]);
                }
                cmd.args([
                    "-c",
                    "copy",
                    "-movflags",
                    "+frag_keyframe+empty_moov+default_base_moof+negative_cts_offsets",
                ])
                .arg(&reference)
                .status()
                .map(|s| s.success())
                .unwrap_or(false)
            };
            // ffmpeg's fragmented muxer cannot remux every audio codec it can
            // decode (AC-3 aborts); the video timing oracle still applies
            let with_audio = has_audio && remux(true);
            if !with_audio {
                assert!(
                    remux(false),
                    "{name}: ffmpeg reference remux failed even for video only"
                );
                if has_audio {
                    eprintln!("    note: {name}: ffmpeg could not remux the audio track; video-only oracle");
                }
            }
            let (rv, ra) = stream_starts(&reference);
            let (ov, oa) = stream_starts(&out_path);
            assert!(
                (rv.unwrap_or(0.0) - ov.unwrap_or(0.0)).abs() < 0.001,
                "{name}: video start {ov:?} vs ffmpeg reference {rv:?}"
            );
            if with_audio {
                if let (Some(r), Some(o)) = (ra, oa) {
                    assert!(
                        (r - o).abs() < 0.001,
                        "{name}: audio start {o} vs ffmpeg reference {r}"
                    );
                }
            }
            let rp = first_video_packets(&reference, 12);
            let op = first_video_packets(&out_path, 12);
            assert_eq!(
                rp, op,
                "{name}: first video packets (pts,dts) differ from ffmpeg reference"
            );
        }

        // playlist consumed by ffprobe; every segment decodes standalone
        let seg_url = |i: usize| format!("seg-{i}.m4s");
        let pl = playlist::media_playlist(&idx, "init.mp4", &seg_url, None);
        let pl_path = tmp.join(format!("{name}.m3u8"));
        std::fs::write(&pl_path, pl).unwrap();
        std::fs::write(tmp.join("init.mp4"), init_bytes(&idx, &src)).unwrap();
        for n in 0..idx.segments.len() {
            std::fs::write(
                tmp.join(format!("seg-{n}.m4s")),
                segment_bytes(&idx, n, &src),
            )
            .unwrap();
        }
        let pl_dur = ffprobe_duration_ms(&pl_path);
        assert!(
            pl_dur.abs_diff(src_duration) <= 200,
            "{name}: ffprobe over playlist reports {pl_dur}ms vs source {src_duration}ms"
        );
        for n in 0..idx.segments.len() {
            let mut one = init_bytes(&idx, &src);
            one.extend(segment_bytes(&idx, n, &src));
            let p = tmp.join(format!("{name}-seg{n}.mp4"));
            std::fs::write(&p, &one).unwrap();
            assert!(
                count_frames(&p, kind_sel) > 0,
                "{name}: segment {n} does not decode standalone"
            );
        }
        eprintln!("--- {name}: OK ({} segments, dur {dur_out}ms, frames {frames_src}/{frames_out}, playlist {pl_dur}ms)", idx.segments.len());
    }
}
