/**
 * The Trusted Types default policy (docs/SECURITY-REVIEW.md › O1).
 *
 * The CSP (web/public/_headers) says `require-trusted-types-for 'script'`:
 * every DOM sink that can turn a string into code — `innerHTML`,
 * `new Worker(url)`, `navigator.serviceWorker.register(url)`, a script's
 * `src` — refuses plain strings and accepts only values minted by a named
 * policy the CSP allows (`trusted-types lit-html default`).
 *
 * Two policies exist in this app, and that is the whole list:
 *
 * - `lit-html` — Lit's own. It only ever receives Lit's *template* strings
 *   (the static parts we wrote), never data: bindings are set as text or
 *   properties. That is why Lit is safe under Trusted Types.
 * - `default` — this file. The browser calls it for any sink that receives
 *   a plain string. It answers exactly one question — "is this one of OUR
 *   script URLs?" — and blocks everything else by returning null (the sink
 *   then throws). It deliberately has NO `createHTML`: an `innerHTML = …`
 *   anywhere in the app fails closed, which is how the last two of them
 *   were found and removed (shared.ts › promptName, s.html's icon).
 *
 * Why a *default* policy instead of wrapping each call site: the worker
 * construction for the local index is generated by Vite
 * (`new Worker(new URL(…, import.meta.url))` is the pattern its bundler
 * recognises), so we do not own that line. The default policy covers it and
 * the service-worker registration without changing either.
 *
 * Browsers without Trusted Types (Firefox, older Safari) skip this; the CSP's
 * other directives still apply there, and the sinks were removed anyway.
 */

/** Same-origin script URLs the app itself loads; nothing else may become a script. */
export function allowedScriptURL(raw: string, origin: string, dev: boolean): string | null {
	let url: URL;
	try {
		url = new URL(raw, origin);
	} catch {
		return null;
	}
	if (url.origin !== origin) return null;
	// The media service worker (shell.ts) — a fixed public file.
	if (url.pathname === "/sw-media.js" && !url.search) return url.href;
	// Vite's hashed chunks: the local-index worker in a production build.
	if (/^\/assets\/[A-Za-z0-9_.-]+\.js$/.test(url.pathname) && !url.search) return url.href;
	// `vite dev` serves the worker from source with a query (?worker_file…).
	if (dev && url.pathname.startsWith("/src/")) return url.href;
	return null;
}

type PolicyFactory = { createPolicy(name: string, rules: { createScriptURL(input: string): string | null }): unknown };

export function installDefaultPolicy(): void {
	const tt = (globalThis as { trustedTypes?: PolicyFactory }).trustedTypes;
	if (!tt) return;
	const dev = Boolean((import.meta as { env?: { DEV?: boolean } }).env?.DEV);
	tt.createPolicy("default", {
		createScriptURL: (input) => {
			const ok = allowedScriptURL(input, location.origin, dev);
			if (!ok) console.error(`Trusted Types: refused script URL ${input}`);
			return ok;
		},
	});
}
